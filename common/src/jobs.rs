/// The state of a job.
#[derive(Clone, Debug, Deserialize, JsonSchema, Serialize)]
pub enum JobStatus {
    Cancelled {
        job_id: JobId,
        time_cancelled: DateTime<Utc>,
        actor: KeyId,
    },
    Queued {
        job_id: JobId,
        time_queued: DateTime<Utc>,
        actor: KeyId,
    },
    Error {
        job_id: JobId,
        time_error: DateTime<Utc>,
        error: ProcessError,
    },
    Started {
        job_id: JobId,
        time_started: DateTime<Utc>,
    },
    Stopped {
        job_id: JobId,
        time_started: DateTime<Utc>,
        time_stopped: DateTime<Utc>,
        result: Result<i32, ProcessError>,
        output: JobOutputState,
    },
    Skipped {
        job_id: JobId,
        time_skipped: DateTime<Utc>,
        reason: SkipReason,
    },
}

impl JobStatus {
    /// Which job this state describes.
    pub fn job_id(&self) -> &JobId {
        match self {
            Self::Cancelled { job_id, .. }
            | Self::Queued { job_id, .. }
            | Self::Error { job_id, .. }
            | Self::Started { job_id, .. }
            | Self::Stopped { job_id, .. }
            | Self::Skipped { job_id, .. } => job_id,
        }
    }

    /// Whether this status can ever change again.
    pub fn is_terminal(&self) -> bool {
        matches!(
            self,
            Self::Cancelled { .. }
                | Self::Error { .. }
                | Self::Stopped { .. }
                | Self::Skipped { .. }
        )
    }

    /// The most recent timestamp recorded for this status.
    pub fn time(&self) -> DateTime<Utc> {
        match self {
            Self::Cancelled { time_cancelled, .. } => *time_cancelled,
            Self::Queued { time_queued, .. } => *time_queued,
            Self::Error { time_error, .. } => *time_error,
            Self::Started { time_started, .. } => *time_started,
            Self::Stopped { time_stopped, .. } => *time_stopped,
            Self::Skipped { time_skipped, .. } => *time_skipped,
        }
    }

    /// How long it spent or has been in this state.
    pub fn time_elapsed(&self) -> TimeDelta {
        match self {
            Self::Cancelled { .. } | Self::Error { .. } | Self::Skipped { .. } => TimeDelta::zero(),
            Self::Queued { time_queued, .. } => Utc::now() - time_queued,
            Self::Started { time_started, .. } => Utc::now() - time_started,
            Self::Stopped {
                time_started,
                time_stopped,
                ..
            } => *time_stopped - time_started,
        }
    }
}

/// Why a sled will never run a job.
#[derive(Clone, Copy, Debug, Deserialize, Eq, JsonSchema, PartialEq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum SkipReason {
    SessionSuperseded,
    SessionEnded,
    NotTargeted,
    CubbyUnknown,
}

impl fmt::Display for SkipReason {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::SessionSuperseded => "another session has superseded this one",
            Self::SessionEnded => "the session ended before the job could start",
            Self::NotTargeted => "the job does not target this sled",
            Self::CubbyUnknown => "this sled does not know its cubby yet",
        })
    }
}

pub type JobStatusMap = BTreeMap<BaseboardId, JobStatus>;
pub type JsonJobStatusMap = HashMap<String, JobStatus>;

/// What's known about a job.
#[derive(Clone, Debug, Deserialize, JsonSchema, Serialize)]
pub struct JobRecord {
    /// The signed job request, or `None` if it is unknown (e.g., the job was skipped).
    pub request: Option<SignedJob>,

    /// The fate of the job, as much as is known via gossip.
    #[serde(with = "status_map")]
    #[schemars(with = "JsonJobStatusMap")]
    pub status: JobStatusMap,
}

/// Helper to de/serialize JSON job status maps.
mod status_map {
    use serde::de::Error as _;
    use serde::{Deserialize, Deserializer, Serializer};

    use super::{JobStatusMap, JsonJobStatusMap, job_status_try_from_json_map};

    pub fn serialize<S: Serializer>(map: &JobStatusMap, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.collect_map(
            map.iter()
                .map(|(baseboard, status)| (baseboard.to_string(), status)),
        )
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(
        deserializer: D,
    ) -> Result<JobStatusMap, D::Error> {
        job_status_try_from_json_map(JsonJobStatusMap::deserialize(deserializer)?)
            .map_err(D::Error::custom)
    }
}

/// This helper fallibly decodes a job status map from a JSON (string-keyed) map.
pub fn job_status_try_from_json_map(
    json_map: JsonJobStatusMap,
) -> Result<JobStatusMap, BaseboardIdParseError> {
    let mut new = JobStatusMap::new();
    for (k, v) in json_map.into_iter() {
        new.insert(BaseboardId::from_str(&k)?, v);
    }
    Ok(new)
}

/// And this one infallibly encodes a job status map into a JSON-compatible map.
pub fn job_status_to_json_map(status_map: JobStatusMap) -> JsonJobStatusMap {
    let mut new = HashMap::new();
    for (k, v) in status_map.into_iter() {
        new.insert(k.to_string(), v);
    }
    new
}

/// What went wrong running a job's process or interactive session.
// We currently squash inner errors into strings to avoid excessive
// derivation requirements, but may come to regret that decision.
#[derive(Clone, Debug, Deserialize, Eq, Error, JsonSchema, PartialEq, Serialize)]
pub enum ProcessError {
    #[error("The fate of the process is unknown")]
    Unknown,
    #[error("Process killed with signal {0}")]
    Killed(i32),
    #[error("Interactive session error: {0}")]
    Interactive(String),
    #[error("Command must not start with `-`")]
    InvalidCommand,
    #[error("Job validation error: {0}")]
    InvalidJob(String),
    #[error("I/O error {what}: {error}")]
    Io { what: String, error: String },
    #[error("{stream} exceeded the output limit of {limit} bytes")]
    OutputLimitExceeded { stream: JobOutputStream, limit: u64 },
    #[error("Unable to join job process: {0}")]
    Join(String),
    #[error("The server restarted while the job was running")]
    Interrupted,
}

impl ProcessError {
    pub fn io(what: impl AsRef<str>, error: IoError) -> Self {
        Self::Io {
            what: what.as_ref().to_owned(),
            error: error.to_string(),
        }
    }
}

