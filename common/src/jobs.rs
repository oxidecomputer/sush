#[derive(Debug, Error)]
#[error("session sequence number exceeds four-word codephrase range")]
pub struct SeqOutOfRange;

impl SessionSeq {
    /// The largest encodable wall clock reading, `zoo-zoo-zoo-zoo`
    /// = 2527-06-23T06:20:44.415Z.
    pub const MAX_MILLIS: u64 = (1 << 44) - 1;

    pub fn zero() -> Self {
        Self(Codephrase::from_u64(0))
    }

    /// Make a sequence number from a wall clock reading. Fails
    /// if millis is out of range.
    pub fn from_unix_millis(millis: u64) -> Result<Self, SeqOutOfRange> {
        if millis > Self::MAX_MILLIS {
            return Err(SeqOutOfRange);
        }
        Ok(Self(Codephrase::from_u64(millis)))
    }

    pub fn as_unix_millis(&self) -> u64 {
        self.0.to_u64().expect("a sequence number is four words")
    }
}

#[derive(Clone, Debug, Default, Deserialize, Eq, JsonSchema, PartialEq, Serialize)]
pub enum LastJob {
    #[default]
    None,
    Some(SignedJob),
    Burned(JobId),
    Resumed(JobId),
}

/// The hash chain of the jobs within a session, and the actor that
/// started it.
#[derive(Clone, Debug, Deserialize, Eq, JsonSchema, PartialEq, Serialize)]
pub struct Session {
    session_id: SessionId,
    last_job: LastJob,
    started_by: Option<KeyId>,
}

impl Session {
    pub fn new(session_id: SessionId) -> Self {
        Self {
            session_id,
            last_job: LastJob::None,
            started_by: None,
        }
    }

    pub fn started(session_id: SessionId, actor: KeyId) -> Self {
        Self {
            session_id,
            last_job: LastJob::None,
            started_by: Some(actor),
        }
    }

    pub fn session_id(&self) -> SessionId {
        self.session_id
    }

    pub fn started_by(&self) -> Option<&KeyId> {
        self.started_by.as_ref()
    }

    pub fn into_session_id(self) -> SessionId {
        self.session_id
    }

    pub fn last_job(&self) -> LastJob {
        self.last_job.clone()
    }

    pub fn job_started(&mut self, job: SignedJob) {
        self.last_job = LastJob::Some(job)
    }

    pub fn next_job_id(&self) -> JobId {
        self.session_id.next_job_id(&self.last_job)
    }

    /// Burn `job_id` when it is the session's next job or the head
    /// of the chain. Returns whether the chain moved.
    pub fn skip_job(&mut self, job_id: JobId) -> bool {
        if job_id == self.next_job_id()
            || matches!(&self.last_job, LastJob::Some(job) if *job.job_id() == job_id)
        {
            self.last_job = LastJob::Burned(job_id);
            true
        } else {
            false
        }
    }

    /// Resume the chain at `successor`, the position a boundary
    /// record stored at its last commitment.
    pub fn resume_at(&mut self, successor: JobId) {
        self.last_job = LastJob::Resumed(successor);
    }
}

